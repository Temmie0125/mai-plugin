/**
 * 定数表 / 定数完成表页面（源 core/image/rating_table.py:153 DrawRatingTable.draw）
 *
 * levelText=true  → 源 `定数表` 指令：仅叠 `Level.` + 定数两行字，**不缩放**（输出 1400 宽）。
 * levelText=false → 源「完成表」：叠统计行、complete.png 与逐格状态，**整图 ×0.8**（输出 1120 宽）。
 *
 * @param {object} opts
 * @param {string} opts.rating 定数字面（"13" / "13+"）
 * @param {object} opts.levelData mai.totalLevelData[rating]
 * @param {boolean} [opts.levelText] true=纯定数表标题模式
 * @param {boolean} [opts.plan] 完成表 fc/ap 计划模式
 * @param {Record<string, number>} [opts.statistics] processRatingTableData 输出
 * @param {Map} [opts.playedMap] processRatingTableData 输出
 * @param {string} opts.botName
 */
export function ratingTableView({
  rating, levelData, levelText = false, plan = false,
  statistics = null, playedMap = null, botName = '',
}) {
  const isLv15 = rating === '15'
  const layout = isLv15 ? level15Layout(levelData?.['15.0']) : ratingTableLayout(levelData)
  const base = isLv15 ? level15BaseLayers(layout, botName) : ratingBaseLayers(layout, botName)
  const images = base.images
  const texts = base.texts

  // 源 level_text 分支：y=220；全分支：y=160（两者均 anchor ld、fot、stroke 8 白）
  const titleY = levelText ? 220 : 160
  texts.push(txt('Level.', 495, titleY, 70,
    { font: 'fot', color: FONT_COLOR, anchor: 'ld', stroke: 8, strokeColor: '#ffffff', z: Z.OV_TEXT }))
  texts.push(txt(rating, 750, titleY, 100,
    { font: 'fot', color: FONT_COLOR, anchor: 'ld', stroke: 8, strokeColor: '#ffffff', z: Z.OV_TEXT }))

  if (!levelText) {
    ratingOverlay({ images, texts, rating, levelData, isLv15, layout, plan, statistics, playedMap })
  }

  const scale = levelText ? 1 : 0.8
  return {
    width: 1400,
    height: layout.height,
    scale,
    cssWidth: Math.trunc(1400 * scale),
    cssHeight: Math.trunc(layout.height * scale),
    pageLeft: 0,
    pageTop: 0,
    bgCss: tricolorGradientCss(),
    card: cardElement(layout.card),
    images,
    texts,
  }
}

/** 完成表叠加层（源 rating_table.py:185-315 全分支） */
function ratingOverlay({ images, texts, rating, levelData, isLv15, layout, plan, statistics, playedMap }) {
  const totalSongsCount = Object.values(levelData ?? {}).reduce((a, b) => a + b.length, 0)
  const achievementsOrFc = []

  // 源 im.alpha_composite(self._table_complete_bg, (251, 190))：垫在统计文字下（z=4 < 文字 5）
  images.push(img(picSrc('complete.png'), 251, 190, null, null, { z: Z.OV_ART }))

  // 首行「已通关数/总数」：源 tb.draw(394, 238, 30, ..., mm, stroke 5 白)
  texts.push(txt(`${statistics.clear}/${totalSongsCount}`, 394, RATING_GRID.statsFirstLineY, 30,
    { font: 'tb', color: DEFAULT_TEXT_COLOR, anchor: 'mm', stroke: 5, strokeColor: '#ffffff', z: Z.OV_TEXT }))
  // 其后 15 项：前 6 项 534+col*102 @238，其余 9 项 292+col*102 @323（源 STATISTICS_KEYS[1:] 遍历）
  const rest = STATISTICS_KEYS.slice(1)
  rest.forEach((key, n) => {
    const x = n < 6
      ? RATING_GRID.statsFirstLineX + (n % 6) * 102
      : RATING_GRID.statsSecondLineX + ((n - 6) % 9) * 102
    const y = n < 6 ? RATING_GRID.statsFirstLineY : RATING_GRID.statsSecondLineY
    texts.push(txt(statistics[key], x, y, 30,
      { font: 'tb', color: DEFAULT_TEXT_COLOR, anchor: 'mm', stroke: 2, strokeColor: '#ffffff', z: Z.OV_TEXT }))
  })

  // 逐格状态
  const cells = isLv15
    ? layout.cells.map(c => ({ song: c.song, x: c.x, y: c.y }))
    : layout.groups.flatMap(g => g.songs.map(c => ({ song: c.song, x: c.x, y: c.y })))

  for (const cell of cells) {
    if (!cell.song) continue
    const record = playedMap?.get(cell.song.song_id)?.get(cell.song.difficulties.level_index)
    if (!record) continue
    const ds = cell.song.difficulties.level_value

    if (!plan) {
      achievementsOrFc.push(record.achievements)
      // 源：≥100% 用 complete_1，否则 unfinished_1（半透明 maxA=179，必须压在底图曲 id 文字之上）
      images.push(img(picSrc(record.achievements >= 100 ? 'complete_1.png' : 'unfinished_1.png'),
        cell.x + 1, cell.y + 1, null, null, { z: Z.CELL }))
      // ⚠️ 不做 lower：图标文件名为展示名（UI_TTR_Rank_SSSp.png）
      const rate = computeRating(ds, record.achievements, { onlyrate: true })
      // lv15 大格用原生 256×120；其余 78×35（源两分支尺寸不同）
      if (isLv15) {
        images.push(img(themedPicSrc('prism_plus', `UI_TTR_Rank_${rate}.png`), cell.x + 55, cell.y + 115, null, null, { z: Z.CELL }))
      } else {
        images.push(img(themedPicSrc('prism_plus', `UI_TTR_Rank_${rate}.png`), cell.x, cell.y + 20, 78, 35, { z: Z.CELL }))
      }
      continue
    }

    if (record.fc) {
      achievementsOrFc.push(COMBO_SP.indexOf(record.fc))
      images.push(img(picSrc('complete_1.png'), cell.x + 1, cell.y + 1, null, null, { z: Z.CELL }))
      if (isLv15) {
        images.push(img(picSrc(`UI_CHR_PlayBonus_${COMBO_MAP[record.fc]}.png`), cell.x + 75, cell.y + 80, 200, 200, { z: Z.CELL }))
      } else {
        images.push(img(picSrc(`UI_MSS_MBase_Icon_${COMBO_MAP[record.fc]}.png`), cell.x + 15, cell.y + 13, 50, 50, { z: Z.CELL }))
      }
    }
  }

  // 全清徽章（源：仅当收集数等于该等级谱面总数时判定；-1 表示未达任何档位）
  if (achievementsOrFc.length === totalSongsCount) {
    const r = calcAchievementsFc(achievementsOrFc, totalSongsCount, plan)
    if (r !== -1) {
      const pic = plan ? COMBO_MAP[COMBO_SP[r]] : RANK_MAP[RANK_SP.slice(-6)[r]]
      images.push(img(picSrc(`UI_MSS_Allclear_Icon_${pic}.png`), 40, 40, null, null, { z: Z.CELL }))
    }
  }
}


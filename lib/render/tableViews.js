/** z 阶梯（见文件头注释，勿逐页自创） */
export const Z = { DECO: 0, CARD: 1, GRID_IMG: 2, BASE_TEXT: 3, OV_ART: 4, OV_TEXT: 5, CELL: 6 }

/** 源 AssetsImage._font_color = (114,188,254,255)（表格族统一字色） */
const FONT_COLOR = '#72bcfe'

/** 源 generate_frosted_card 默认参数；表格卡面积远大于 songlist 卡，alpha 需按页标定（见 B4） */
export const FROSTED = {
  radius: 25, alpha: 0.4, blur: 4,
  shadow: '10px 10px 12px rgba(0, 0, 0, 0.20)',
}

/**
 * 源 update_table.py:_generate_bg —— 装饰底（渐变由 CSS 承担，其余为按坐标铺的贴图）
 * @param {number} height 源坐标空间高度
 * @param {number|null} separatorHeight separator.png 的 y（定数表 360 / 完成表 400）；null 不画
 */
export function tableBgLayers(height, separatorHeight = null) {
  const images = [
    img(picSrc('aurora.png'), 0, 0, null, null, { z: Z.DECO }),
    img(picSrc('bg_shines.png'), 11, 6, null, null, { z: Z.DECO }),
    img(picSrc('rainbow.png'), 318, height - 545, null, null, { z: Z.DECO }),
    img(picSrc('rainbow_bottom.png'), 122, height - 305, null, null, { z: Z.DECO }),
  ]
  // 源 for h in range(height // 358 + 1): pattern 落在 (0, (358+7)*h)
  for (let h = 0; h <= Math.floor(height / 358); h++) {
    images.push(img(picSrc('pattern.png'), 0, 365 * h, null, null, { z: Z.DECO }))
  }
  if (separatorHeight !== null) {
    images.push(img(picSrc('separator.png'), 100, separatorHeight, null, null, { z: Z.DECO }))
  }
  return images
}

/** 源 generate_frosted_card 的卡片数据（含属性，模板只负责打印） */
export function cardElement(card) {
  return { ...card, ...FROSTED, z: Z.CARD }
}


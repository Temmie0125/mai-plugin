/** 源 plate_table.py:331 _get_plate_icon —— 达成图标的来源与尺寸随计划而变 */
function plateIcon(play, plan) {
  if (plan === '将' || plan === '者') {
    // ⚠️ 与统计侧不同，此处**不做 lower**（文件名就是 UI_TTR_Rank_SSS.png）
    const rate = computeRating(play.level_value, play.achievements, { onlyrate: true })
    return { src: themedPicSrc('prism_plus', `UI_TTR_Rank_${rate}.png`), w: 80, h: 36 }
  }
  const cfg = PLAN_CRITERIA[plan]
  const val = play[cfg.attr]
  const iconName = COMBO_MAP[val] ?? SYNC_MAP[val] ?? val
  return { src: picSrc(`${cfg.prefix}${iconName}.png`), w: 60, h: 60 }
}

/**
 * 版本称号完成表页面（源 plate_table.py:346 DrawPlateTable.draw）
 *
 * 底图仍是「本插件按源 update_table.py 坐标重画」（ADR-7），源坐标空间 1400 宽，**不做缩放**。
 * 底图取当前页的等级集合（舞-1/舞-2 各自成页），与源的 `plate_table/舞-{page}.png` 同构。
 *
 * @param {object} o
 * @param {string} o.version 短版本字（贴图路径用，源 _plate_background 亦用短字）
 * @param {string} o.versionName VERSION_MAP 版本名
 * @param {boolean} o.isWu
 * @param {number} o.page 1 基页码（仅舞）
 * @param {string} o.plan 称号字
 * @param {object} o.data processPlateTable 输出
 * @param {Set<number>} o.remasterIdSet 舞ReMASTER id 集
 * @param {string} o.botName
 */
export function plateTableView({
  version, isWu, page, plan, data, remasterIdSet = null, botName = '',
}) {
  // 底图只含当前页等级（源底图按页预生成），这样叠加层的 y 与底图网格逐格对齐
  const buckets = [...data.levels.entries()]
    .filter(([level]) => data.displaySet.has(level))
    .map(([level, rows]) => ({
      level,
      songs: rows.map(r => data.songsById.get(r.song_id)).filter(Boolean),
    }))
  const layout = plateTableLayout(buckets, { pages: isWu ? page - 1 : null, remasterIdSet })

  const images = tableBgLayers(layout.height, layout.separatorHeight)
  const texts = []
  // 底图网格（与 ratingBaseLayers 同构，但间距 96 / 曲绘 80 / 曲 id 字号 16）
  for (const g of layout.groups) {
    texts.push(txt(g.level, g.labelX, g.labelY, 40,
      { font: 'fot', color: FONT_COLOR, anchor: 'lm', stroke: 4, strokeColor: '#ffffff', z: Z.BASE_TEXT }))
    for (const cell of g.songs) {
      images.push(img(songChartSrc(cell.song.song_id), cell.x, cell.y, 80, 80, { z: Z.GRID_IMG }))
      // 白谱（舞ReMASTER）用另一套 id 底板与紫色字（源 _draw_plate）
      images.push(img(picSrc(cell.isRemaster ? 'border_table_remaster.png' : 'border_table_base.png'),
        cell.x - 5, cell.y - 5, null, null, { z: Z.GRID_IMG }))
      texts.push(txt(cell.song.song_id, cell.x + 56, cell.y + 4, 16,
        { font: 'tb', color: cell.isRemaster ? '#8a00e2' : '#ffffff', anchor: 'mm', z: Z.BASE_TEXT }))
    }
  }
  // 舞/霸者底图特有：源 update_table.py:_draw_plate 的 `Pages {n}/2`（仅 pages 非 None 时）
  if (layout.pagesText) {
    texts.push(txt(layout.pagesText.text, layout.pagesText.x, layout.pagesText.y, 40,
      { font: 'fot', color: FONT_COLOR, anchor: 'mm', z: Z.BASE_TEXT }))
  }
  texts.push(footerElement(layout.footer, botName))

  // ---- 叠加层：进度条 / 牌子徽章 / 统计 ----
  const progressBg = isWu ? 'plate_progress_wu.png' : 'plate_progress.png'
  images.push(img(picSrc(progressBg), 175, 20, null, null, { z: Z.OV_ART }))

  const plateArt = maiSrc('plate_version', `${version}${platePlanChar(plan)}.png`)
  // 源遇缺图抛 FileNotFoundError → @handle_errors 复刻为通用错误文案；
  // <img> 坏 src 只会画破图占位符，故此处主动抛错（R5）
  if (!fs.existsSync(picSrcToPath(plateArt))) {
    throw new Error(`plate_version art missing: ${version}${platePlanChar(plan)}.png`)
  }
  images.push(img(plateArt, 200, 45, 1000, 161, { z: Z.OV_ART }))

  const progressWidth = isWu ? 176 : 230
  const statsStartX = isWu ? 292 : 320
  const statsGapX = isWu ? 204 : 253
  const progressTextX = isWu ? 89 : 115
  const progressX = isWu ? 88 : 115

  for (const g of layout.groups) {
    for (const cell of g.songs) {
      const row = data.levels.get(g.level)?.find(r => r.song_id === cell.song.song_id)
      if (!row) continue
      const index = row.results.length - 1
      // 源：仅当「最高难度槽位」达标时才画大字图标
      if (row.qualified_slots.includes(index)) {
        images.push(img(picSrc('complete_2.png'), cell.x + 1, cell.y + 1, null, null, { z: Z.CELL }))
        const icon = plateIcon(row.results[index], plan)
        const dx = plan === '将' || plan === '者' ? 0 : 10
        const dy = plan === '将' || plan === '者' ? 22 : 12
        images.push(img(icon.src, cell.x + dx, cell.y + dy, icon.w, icon.h, { z: Z.CELL }))
      }
      for (const sIdx of row.qualified_slots) {
        if (isWu && row.results.length === 5) {
          images.push(img(picSrc(`t_${sIdx}.png`), cell.x + 1 + 16 * sIdx, cell.y + 64, 14, 14, { z: Z.CELL }))
        } else {
          images.push(img(picSrc(`t_${sIdx}.png`), cell.x + 4 + 19 * sIdx, cell.y + 63, null, null, { z: Z.CELL }))
        }
      }
    }
  }

  const completeSum = data.completedCount
  const total = data.totalCount
  const text = completeSum === total ? 'COMPLETED!!!' : `${completeSum}/${total}`
  const progress = total === 0 ? 0 : completeSum / total
  if (progress !== 0) {
    images.push(img(picSrc('progress_big.png'), 204, 219, Math.trunc(993 * progress), 92,
      { crop: true, z: Z.OV_ART }))
  }
  texts.push(txt(text, 700, 240, 30,
    { font: 'fot', color: DEFAULT_TEXT_COLOR, anchor: 'mm', stroke: 3, strokeColor: '#ffffff', z: Z.OV_TEXT }))
  texts.push(txt(`${pyRound2(progress * 100)}%`, 1190, 240, 30,
    { font: 'fot', color: DEFAULT_TEXT_COLOR, anchor: 'rm', stroke: 3, strokeColor: '#ffffff', z: Z.OV_TEXT }))

  data.slotCounts.forEach((completeSumGroup, l) => {
    const x = statsStartX + l * statsGapX
    const plateCount = l !== 4 ? total : data.remasterCount
    if (!plateCount) return
    const progressGroup = completeSumGroup / plateCount
    if (progressGroup !== 0) {
      images.push(img(picSrc(isWu ? 'progress_small_wu.png' : 'progress_small.png'),
        x - progressX, 326, Math.trunc(progressWidth * progressGroup), 46, { crop: true, z: Z.OV_ART }))
    }
    texts.push(txt(completeSumGroup, x, 300, 40,
      { font: 'fot', color: ID_TEXT_COLOR[l], anchor: 'mm', stroke: 4, strokeColor: '#ffffff', z: Z.OV_TEXT }))
    texts.push(txt(`/${plateCount}`, x + progressTextX, 320, 14,
      { font: 'fot', color: ID_TEXT_COLOR[l], anchor: 'rd', stroke: 3, strokeColor: '#ffffff', z: Z.OV_TEXT }))
    texts.push(txt(`${pyRound2(progressGroup * 100)}%`, x + progressTextX, 343, 20,
      { font: 'fot', color: DEFAULT_TEXT_COLOR, anchor: 'rm', stroke: 2, strokeColor: '#ffffff', z: Z.OV_TEXT }))
  })

  return {
    width: 1400,
    height: layout.height,
    scale: 1,
    cssWidth: 1400,
    cssHeight: layout.height,
    pageLeft: 0,
    pageTop: 0,
    bgCss: tricolorGradientCss(),
    card: cardElement(layout.card),
    images,
    texts,
  }
}


/**
 * 表格族页面构建器（源 core/image/{update_table,rating_table,plate_table}.py 坐标直译）
 * 视觉设计派生自 nonebot-plugin-maimaidx（Yuri-YuzuChaN）及上游 mai-bot。
 *
 * ADR-7：源把这两页叠在 `更新定数表`/`更新完成表` 命令**运行时预生成**的整页底图上，
 * 那批 PNG 是本机产物、不在上游资源包内 —— 本模块按源生成器（update_table.py）**同一套坐标**
 * 在 HTML/CSS 侧重画底图（渐变 + 毛玻璃卡 + 曲绘网格），再叠用户相关层。
 * 布局算术全部来自 lib/tableLayout.js，本文件只负责「按源的调用顺序产出渲染元素」。
 *
 * ⚠️ z 阶梯（比源多出来的唯一一处显式建模）：PIL 严格按调用序叠层，而 CSS 需要显式 z；
 * 且 complete_1/unfinished_1/complete_2 是**半透明**（实测 maxA=179）并压在底图曲 id 文字之上，
 * 压错层不是轻微色偏而是每个已游玩格一片 hard 格。故统一：装饰 0 / 卡片 1 / 网格图 2 /
 * 底图文字 3 / 叠加贴图 4 / 叠加文字 5 / 逐格状态 6。
 */

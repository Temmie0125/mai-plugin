/**
 * 定数表底图（源 update_table.py:121 的绘制部分）
 * @param {object} layout lib/tableLayout.js 的 ratingTableLayout 输出
 * @param {string} botName
 */
function ratingBaseLayers(layout, botName) {
  const images = tableBgLayers(layout.height, layout.separatorHeight)
  const texts = []
  for (const g of layout.groups) {
    // 源 fot.draw(70, START_Y + 35, 40, f".{ds.split('.')[-1]}", ..., lm, stroke 4 white)
    texts.push(txt(`.${g.ds.split('.')[1]}`, g.labelX, g.labelY, 40,
      { font: 'fot', color: FONT_COLOR, anchor: 'lm', stroke: 4, strokeColor: '#ffffff', z: Z.BASE_TEXT }))
    for (const cell of g.songs) {
      const li = cell.song.difficulties.level_index
      images.push(img(songChartSrc(cell.song.song_id), cell.x, cell.y, 75, 75, { z: Z.GRID_IMG }))
      // 难度边框压在曲绘之上（源先 composite cover 再 composite border）
      images.push(img(picSrc(`border_${DIFF_BG_NAMES[li]}.png`), cell.x - 5, cell.y - 5, null, null, { z: Z.GRID_IMG }))
      texts.push(txt(cell.song.song_id, cell.x + 56, cell.y + 4, 13,
        { font: 'tb', color: DIFF_TEXT_COLOR[li], anchor: 'mm', z: Z.BASE_TEXT }))
    }
  }
  texts.push(footerElement(layout.footer, botName))
  return { images, texts }
}

